const TRANSLATIONS = {
  fa: FA,
  en: EN,
  az: AZ,
  tr: TR
};

const FALLBACK_CHAIN = {
  fa: ["fa"],
  en: ["en", "fa"],
  az: ["az", "en", "fa"],
  tr: ["tr", "en", "fa"]
};

export function resolveLanguage({ savedLanguage } = {}) {
  if (SUPPORTED_LANGUAGES.includes(savedLanguage)) {
    return savedLanguage;
  }
  return "fa";
}

export function createI18n(initialLanguage = "fa") {
  let currentLanguage = SUPPORTED_LANGUAGES.includes(initialLanguage) ? initialLanguage : "fa";

  function t(key, params = {}) {
    const chain = FALLBACK_CHAIN[currentLanguage] || FALLBACK_CHAIN.fa;
    let template = key;

    for (const langCode of chain) {
      const dict = TRANSLATIONS[langCode];
      if (!dict) continue;
      if (Object.prototype.hasOwnProperty.call(dict, key)) {
        template = dict[key];
        break;
      }
    }

    return String(template).replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? ""));
  }

  return {
    t,
    getLanguage() {
      return currentLanguage;
    },
    setLanguage(nextLanguage) {
      if (SUPPORTED_LANGUAGES.includes(nextLanguage)) {
        currentLanguage = nextLanguage;
      }
      return currentLanguage;
    },
    getDayNames() {
      return DAYS[currentLanguage] || DAYS.fa;
    },
    getLocale() {
      return LOCALE_BY_LANGUAGE[currentLanguage] || LOCALE_BY_LANGUAGE.fa;
    },
    getDirection() {
      return RTL_LANGUAGES.has(currentLanguage) ? "rtl" : "ltr";
    },
    getSupportedLanguages() {
      return [...SUPPORTED_LANGUAGES];
    }
  };
}
